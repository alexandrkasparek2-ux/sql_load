import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { join } from 'node:path';

const IN_DIR = process.env.IN_DIR || 'migration-export';
const OUT_FILE = process.env.OUT_FILE || join(IN_DIR, 'turso-import.sql');

const TABLES = [
  'profiles',
  'food_entries',
  'training_days',
  'weight_log',
  'user_settings',
  'supplement_log',
  'daily_nutrition_snapshots',
  'race_events',
  'nutrition_targets',
  'training_load_daily',
  'on_bike_nutrition_log',
];

const INSERT_ORDER = [
  'app_users',
  'profiles',
  'race_events',
  'food_entries',
  'training_days',
  'weight_log',
  'user_settings',
  'supplement_log',
  'daily_nutrition_snapshots',
  'nutrition_targets',
  'training_load_daily',
  'on_bike_nutrition_log',
];

const JSON_COLUMNS = new Set([
  'extra_types',
  'activity_hours',
  'activity_intensity',
  'value',
]);

function normalizeRow(table, row) {
  const next = { ...row };

  if (table === 'supplement_log' && typeof next.taken === 'boolean') {
    next.taken = next.taken ? 1 : 0;
  }

  for (const column of JSON_COLUMNS) {
    if (column in next && typeof next[column] !== 'string') {
      next[column] = JSON.stringify(next[column] ?? (column === 'extra_types' ? [] : {}));
    }
  }

  return next;
}

function sqlValue(value) {
  if (value === null || value === undefined) return 'null';
  if (typeof value === 'number') return Number.isFinite(value) ? String(value) : 'null';
  if (typeof value === 'boolean') return value ? '1' : '0';
  if (typeof value === 'object') value = JSON.stringify(value);
  return `'${String(value).replaceAll("'", "''")}'`;
}

async function readRows(table) {
  const file = join(IN_DIR, `${table}.json`);
  if (!existsSync(file)) return [];
  return JSON.parse(await readFile(file, 'utf8')).map(row => normalizeRow(table, row));
}

function insertStatement(table, rows) {
  if (rows.length === 0) return '';
  const columns = Object.keys(rows[0]);
  const values = rows
    .map(row => `  (${columns.map(column => sqlValue(row[column])).join(', ')})`)
    .join(',\n');

  return [
    `insert or ignore into ${table} (${columns.join(', ')}) values`,
    `${values};`,
    '',
  ].join('\n');
}

await mkdir(IN_DIR, { recursive: true });

const tableRows = {};
const userIds = new Set();

for (const table of TABLES) {
  const rows = await readRows(table);
  tableRows[table] = rows;
  for (const row of rows) {
    if (row.user_id) userIds.add(row.user_id);
    if (table === 'profiles' && row.id) userIds.add(row.id);
  }
}

tableRows.app_users = [...userIds].sort().map(id => ({
  id,
  email: null,
  display_name: null,
}));

const output = [
  '-- Generated by scripts/build-turso-import-sql.mjs',
  '-- Run db/migrations/001_cyclofuel_turso_schema.sql first.',
  'pragma foreign_keys = on;',
  'begin transaction;',
  '',
  ...INSERT_ORDER.map(table => insertStatement(table, tableRows[table] ?? [])),
  'commit;',
  '',
].join('\n');

await writeFile(OUT_FILE, output);
console.log(`Turso import SQL written to ${OUT_FILE}`);
