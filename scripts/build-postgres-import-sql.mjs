import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { join } from 'node:path';

const IN_DIR = process.env.IN_DIR || 'migration-export';
const OUT_FILE = process.env.OUT_FILE || join(IN_DIR, 'import-data.sql');

const TABLES = [
  'profiles',
  'food_entries',
  'training_days',
  'weight_log',
  'user_settings',
  'supplement_log',
  'daily_nutrition_snapshots',
  'race_events',
  'nutrition_targets',
  'training_load_daily',
  'on_bike_nutrition_log',
];

const INSERT_ORDER = [
  'app_users',
  'profiles',
  'race_events',
  'food_entries',
  'training_days',
  'weight_log',
  'user_settings',
  'supplement_log',
  'daily_nutrition_snapshots',
  'nutrition_targets',
  'training_load_daily',
  'on_bike_nutrition_log',
];

function sqlValue(value) {
  if (value === null || value === undefined) return 'null';
  if (typeof value === 'number') return Number.isFinite(value) ? String(value) : 'null';
  if (typeof value === 'boolean') return value ? 'true' : 'false';
  if (Array.isArray(value)) return `array[${value.map(v => sqlValue(v)).join(', ')}]::text[]`;
  if (typeof value === 'object') return `'${JSON.stringify(value).replaceAll("'", "''")}'::jsonb`;
  return `'${String(value).replaceAll("'", "''")}'`;
}

async function readRows(table) {
  const file = join(IN_DIR, `${table}.json`);
  if (!existsSync(file)) return [];
  return JSON.parse(await readFile(file, 'utf8'));
}

function insertStatement(table, rows) {
  if (rows.length === 0) return '';
  const columns = Object.keys(rows[0]);
  const values = rows
    .map(row => `  (${columns.map(column => sqlValue(row[column])).join(', ')})`)
    .join(',\n');

  return [
    `insert into ${table} (${columns.join(', ')}) values`,
    values,
    'on conflict do nothing;',
    '',
  ].join('\n');
}

await mkdir(IN_DIR, { recursive: true });

const tableRows = {};
const userIds = new Set();

for (const table of TABLES) {
  const rows = await readRows(table);
  tableRows[table] = rows;
  for (const row of rows) {
    if (row.user_id) userIds.add(row.user_id);
    if (table === 'profiles' && row.id) userIds.add(row.id);
  }
}

tableRows.app_users = [...userIds].sort().map(id => ({
  id,
  email: null,
  display_name: null,
}));

const output = [
  '-- Generated by scripts/build-postgres-import-sql.mjs',
  '-- Run 001_cyclofuel_schema.sql first.',
  'begin;',
  'set constraints all deferred;',
  '',
  ...INSERT_ORDER.map(table => insertStatement(table, tableRows[table] ?? [])),
  'commit;',
  '',
].join('\n');

await writeFile(OUT_FILE, output);
console.log(`Import SQL written to ${OUT_FILE}`);
